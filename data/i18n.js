window.MT = window.MT || {};

MT.lang = 'zh';
try { MT.lang = localStorage.getItem('mt_lang') || 'zh'; } catch (e) { /* 無法使用本機儲存時用預設值 */ }

MT.setLang = function (lang) {
  MT.lang = lang;
  try { localStorage.setItem('mt_lang', lang); } catch (e) { /* ignore */ }
};

MT.fmtMoney = function (n) {
  const sign = n < 0 ? '-' : '';
  return sign + 'NT$' + Math.abs(Math.round(n)).toLocaleString('en-US');
};

// 取出雙語物件中目前語言的文字
MT.L = function (obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[MT.lang] != null ? obj[MT.lang] : obj.zh;
};

// 介面字串，參數可以是 {money: n}、雙語物件或一般值
MT.t = function (key, params) {
  let s = MT.STR[MT.lang][key];
  if (s == null) s = MT.STR.zh[key];
  if (s == null) return key;
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => {
      const v = params[k];
      if (v == null) return m;
      if (typeof v === 'object' && 'money' in v) return MT.fmtMoney(v.money);
      if (typeof v === 'object' && v.key) return MT.t(v.key, v);
      if (typeof v === 'object') return MT.L(v);
      return String(v);
    });
  }
  return s;
};

